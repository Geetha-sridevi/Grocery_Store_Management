CREATE DATABASE GroceryStoreDB;

USE GroceryStoreDB;
CREATE TABLE supplier (
    sup_id TINYINT AUTO_INCREMENT PRIMARY KEY,
    sup_name VARCHAR(255),
    address TEXT
);
select * from supplier;

CREATE TABLE categories (
    cat_id TINYINT AUTO_INCREMENT PRIMARY KEY,
    cat_name VARCHAR(255)
);
select * from categories;

CREATE TABLE employees (
    emp_id TINYINT AUTO_INCREMENT PRIMARY KEY,
    emp_name VARCHAR(255),
    hire_date VARCHAR(255)
);
select * from employees;

CREATE TABLE customers (
    cust_id SMALLINT AUTO_INCREMENT PRIMARY KEY,
    cust_name VARCHAR(255),
    address TEXT
);
select * from customers;

CREATE TABLE products (
    prod_id TINYINT AUTO_INCREMENT PRIMARY KEY,
    prod_name VARCHAR(255),
    sup_id TINYINT,
    cat_id TINYINT,
    price DECIMAL(10,2),

    FOREIGN KEY (sup_id)
        REFERENCES supplier(sup_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    FOREIGN KEY (cat_id)
        REFERENCES categories(cat_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);
select * from products;

CREATE TABLE orders (
    ord_id SMALLINT AUTO_INCREMENT PRIMARY KEY,
    cust_id SMALLINT,
    emp_id TINYINT,
    order_date VARCHAR(255),

    FOREIGN KEY (cust_id)
        REFERENCES customers(cust_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    FOREIGN KEY (emp_id)
        REFERENCES employees(emp_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);
select * from orders;

CREATE TABLE order_details (
    ord_detID SMALLINT AUTO_INCREMENT PRIMARY KEY,
    ord_id SMALLINT,
    prod_id TINYINT,
    quantity TINYINT,
    each_price DECIMAL(10,2),
    total_price DECIMAL(10,2),

    FOREIGN KEY (ord_id)
        REFERENCES orders(ord_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    FOREIGN KEY (prod_id)
        REFERENCES products(prod_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);
select * from order_details;
SHOW TABLES;


-- 1️. Customer Insights --
-- Q1. How many unique customers have placed orders?
SELECT COUNT(DISTINCT cust_id) AS unique_customers
FROM orders;

-- Q2. Which customers placed the highest number of orders?
SELECT
    c.cust_name,
    COUNT(o.ord_id) AS total_orders
FROM customers c
JOIN orders o
    ON c.cust_id = o.cust_id
GROUP BY c.cust_id, c.cust_name
ORDER BY total_orders DESC;

-- Q3. Total and average purchase value per customer
SELECT
    c.cust_name,
    SUM(od.total_price) AS total_purchase,
    AVG(od.total_price) AS average_purchase
FROM customers c
JOIN orders o
    ON c.cust_id = o.cust_id
JOIN order_details od
    ON o.ord_id = od.ord_id
GROUP BY c.cust_id, c.cust_name;

-- Q4. Top 5 customers by total purchase amount
SELECT
    c.cust_name,
    SUM(od.total_price) AS total_purchase
FROM customers c
JOIN orders o
    ON c.cust_id = o.cust_id
JOIN order_details od
    ON o.ord_id = od.ord_id
GROUP BY c.cust_id, c.cust_name
ORDER BY total_purchase DESC
LIMIT 5;

-- 2. Product Performance-- 

-- Q1. Number of products in each category
SELECT
    c.cat_name,
    COUNT(p.prod_id) AS product_count
FROM categories c
LEFT JOIN products p
    ON c.cat_id = p.cat_id
GROUP BY c.cat_id, c.cat_name;

-- Q2. Average product price by category
SELECT
    c.cat_name,
    AVG(p.price) AS average_price
FROM categories c
JOIN products p
    ON c.cat_id = p.cat_id
GROUP BY c.cat_id, c.cat_name;
-- Q3. Products with highest sales volume
-- Sales volume = Quantity.

SELECT
    p.prod_name,
    SUM(od.quantity) AS total_quantity
FROM products p
JOIN order_details od
    ON p.prod_id = od.prod_id
GROUP BY p.prod_id, p.prod_name
ORDER BY total_quantity DESC;

-- Q4. Total revenue generated by each product
SELECT
    p.prod_name,
    SUM(od.total_price) AS total_revenue
FROM products p
JOIN order_details od
    ON p.prod_id = od.prod_id
GROUP BY p.prod_id, p.prod_name
ORDER BY total_revenue DESC;

-- Q5. Product sales by category and supplier
SELECT
    c.cat_name,
    s.sup_name,
    SUM(od.quantity) AS total_quantity,
    SUM(od.total_price) AS total_revenue
FROM categories c
JOIN products p
    ON c.cat_id = p.cat_id
JOIN supplier s
    ON p.sup_id = s.sup_id
JOIN order_details od
    ON p.prod_id = od.prod_id
GROUP BY c.cat_id, c.cat_name,
         s.sup_id, s.sup_name
ORDER BY total_revenue DESC;

-- 3. Sales and Order Trends -- 

-- Q1. Total number of orders
SELECT COUNT(*) AS total_orders
FROM orders;

-- Q2. Average order value
SELECT AVG(order_total) AS average_order_value
FROM (
    SELECT
        ord_id,
        SUM(total_price) AS order_total
    FROM order_details
    GROUP BY ord_id
) AS x;

-- Q3. Dates with most orders
SELECT
    order_date,
    COUNT(*) AS total_orders
FROM orders
GROUP BY order_date
ORDER BY total_orders DESC;

-- Q4. Monthly order volume and revenue
-- If date is YYYY-MM-DD:

SELECT
    DATE_FORMAT(STR_TO_DATE(order_date, '%Y-%m-%d'), '%Y-%m') AS month,
    COUNT(DISTINCT o.ord_id) AS total_orders,
    SUM(od.total_price) AS revenue
FROM orders o
JOIN order_details od
    ON o.ord_id = od.ord_id
GROUP BY month
ORDER BY month;

-- Q5. Weekdays vs Weekends
SELECT
    CASE
        WHEN DAYOFWEEK(
            STR_TO_DATE(order_date, '%Y-%m-%d')
        ) IN (1,7)
        THEN 'Weekend'
        ELSE 'Weekday'
    END AS day_type,
    COUNT(*) AS total_orders
FROM orders
GROUP BY day_type;

-- 4️. Supplier Contribution --

-- Q1. Number of suppliers
SELECT COUNT(*) AS total_suppliers
FROM supplier;

-- Q2. Supplier providing most products
SELECT
    s.sup_name,
    COUNT(p.prod_id) AS product_count
FROM supplier s
JOIN products p
    ON s.sup_id = p.sup_id
GROUP BY s.sup_id, s.sup_name
ORDER BY product_count DESC;

-- Q3. Average price from each supplier
SELECT
    s.sup_name,
    AVG(p.price) AS average_price
FROM supplier s
JOIN products p
    ON s.sup_id = p.sup_id
GROUP BY s.sup_id, s.sup_name;

-- Q4. Suppliers contributing most revenue
SELECT
    s.sup_name,
    SUM(od.total_price) AS total_revenue
FROM supplier s
JOIN products p
    ON s.sup_id = p.sup_id
JOIN order_details od
    ON p.prod_id = od.prod_id
GROUP BY s.sup_id, s.sup_name
ORDER BY total_revenue DESC;

-- 5️. Employee Performance -- 

-- Q1. How many employees processed orders?
SELECT COUNT(DISTINCT emp_id) AS employees_processed_orders
FROM orders;

-- Q2. Employees handling most orders
SELECT
    e.emp_name,
    COUNT(o.ord_id) AS total_orders
FROM employees e
JOIN orders o
    ON e.emp_id = o.emp_id
GROUP BY e.emp_id, e.emp_name
ORDER BY total_orders DESC;

-- Q3. Total sales value processed by each employee
SELECT
    e.emp_name,
    SUM(od.total_price) AS total_sales
FROM employees e
JOIN orders o
    ON e.emp_id = o.emp_id
JOIN order_details od
    ON o.ord_id = od.ord_id
GROUP BY e.emp_id, e.emp_name
ORDER BY total_sales DESC;

-- Q4. Average order value handled per employee
SELECT
    e.emp_name,
    AVG(order_total) AS average_order_value
FROM employees e
JOIN orders o
    ON e.emp_id = o.emp_id
JOIN (
    SELECT
        ord_id,
        SUM(total_price) AS order_total
    FROM order_details
    GROUP BY ord_id
) x
    ON o.ord_id = x.ord_id
GROUP BY e.emp_id, e.emp_name
ORDER BY average_order_value DESC;

-- 6️. Order Details Deep Dive -- 

-- Q1. Relationship between quantity and total price
SELECT
    quantity,
    SUM(total_price) AS total_sales
FROM order_details
GROUP BY quantity
ORDER BY quantity;

-- Q2. Average quantity ordered per product
SELECT
    p.prod_name,
    AVG(od.quantity) AS average_quantity
FROM products p
JOIN order_details od
    ON p.prod_id = od.prod_id
GROUP BY p.prod_id, p.prod_name
ORDER BY average_quantity DESC;

-- Q3. Unit price variation across products and orders
SELECT
    p.prod_name,
    MIN(od.each_price) AS minimum_price,
    MAX(od.each_price) AS maximum_price,
    AVG(od.each_price) AS average_price
FROM products p
JOIN order_details od
    ON p.prod_id = od.prod_id
GROUP BY p.prod_id, p.prod_name
ORDER BY p.prod_name;